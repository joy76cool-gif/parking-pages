def 數(s):
    m = re.findall(r'\d+', (s or '').replace(',', ''))
    return int(m[0]) if m else None

def 每月租金(t, 車, 機):
    t2 = t.replace(',', '')
    m = re.search(r'起\s*([\d.]+)\s*萬', t2)
    if m: return float(m.group(1)) * 1e4, f'原文「{t}」→ 用現在的金額 {m.group(1)} 萬', None
    m = re.search(r'月租\s*([\d.]+)\s*萬', t2)
    if m: return float(m.group(1)) * 1e4, f'原文「{t}」', None
    m = re.search(r'月租\s*([\d.]+)\s*元', t2)
    if m: return float(m.group(1)), f'原文「{t}」', None
    m = re.search(r'([\d.]+)\s*萬元／(\d+)\s*年', t2)
    if m:
        y = int(m.group(2)); return float(m.group(1)) * 1e4 / (y * 12), f'原文「{t}」→ {m.group(1)} 萬 ÷ {y} 年 ÷ 12 個月', y
    m = re.search(r'(\d+)\s*年定額不低於\s*([\d.]+)\s*萬', t2)
    if m:
        y = int(m.group(1)); return float(m.group(2)) * 1e4 / (y * 12), f'原文「{t}」→ {m.group(2)} 萬 ÷ {y * 12} 個月（土地租金另計）', y
    m = re.search(r'每年不低於\s*([\d.]+)\s*萬', t2)
    if m: return float(m.group(1)) * 1e4 / 12, f'原文「{t}」→ {m.group(1)} 萬 ÷ 12（變動權利金另計）', None
    m = re.search(r'汽車\s*≥\s*(\d+).*?機車\s*≥\s*(\d+)', t2)
    if m: return 車 * int(m.group(1)) + (機 or 0) * int(m.group(2)), f'原文「{t}」→ 汽車 {車} × {m.group(1)} ＋ 機車 {機 or 0} × {m.group(2)}（第 3 年起再加營收 5%）', None
    return None, f'原文「{t or "空白"}」→ 算不出每月租金', None

