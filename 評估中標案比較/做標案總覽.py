def 做卡(基本, 車, 租, 租說明, 年, 年來源, 核對, 提醒, 完整=None):
    月數 = 年 * 12
    營 = 車 * 台中每格營收
    營運 = 車 * 營運每格
    設備 = 每場設備 / 月數
    費 = 營 * 手續費
    成 = 營運 + 設備 + 費
    完整 = (租 is not None and '另計' not in 租說明 and '再加' not in 租說明) if 完整 is None else 完整
    y = dict(基本, 車=車, 租=租, 營=round(營), 成=round(成), 完整=完整, 核對=核對, 提醒=提醒)
    y['淨'] = round(營 - 成 - 租) if 租 is not None else None
    y['打平每格'] = round((租 + 營運 + 設備) / (1 - 手續費) / 車, 2) if 租 is not None else None
    y['最多能付'] = round(營 - 成)
    y['算式'] = {
        '營': f'{車} 格 × {台中每格營收}（台中 23 個汽車場每格每月營收中位數，未稅，2025/10～2026/9）＝ {f(round(營, 2))}',
        '成': (f'營運費和客服：{車} 格 × {營運每格:.2f}（台中自營場每場每月 {f(每場營運)} ÷ 平均 {台中平均格} 格；Joy 11/11 定全部照格數放大）＝ {f(round(營運, 2))}<br>'
              f'設備攤提：一套 {f(每場設備)}（台中汽車場，W51）÷ {月數} 個月（{年來源}）＝ {f(round(設備, 2))}<br>'
              f'刷卡等手續費：營業額 × 1.64% ＝ {f(round(費, 2))}<br>合計 ＝ {f(round(成, 2))}'),
        '租': (租說明 + (f' ＝ 每月 {f(round(租, 2))}' if 租 is not None else '') + '；稅別未確認' + ('' if 完整 or 租 is None else '；<b>租金只算到已知的下限，實際要付更多，所以淨收入會比這裡少</b>')),
        '淨': (f'{f(round(營))} − {f(round(成))} − {f(round(租))} ＝ {f(y["淨"])}' if 租 is not None else '租金未知，算不出'),
        '打平': (f'（租金 {f(round(租))} ＋ 營運費 {f(round(營運))} ＋ 設備攤提 {f(round(設備))}）÷ (1 − 1.64%) ÷ {車} 格 ＝ {f(y["打平每格"])}；台中中位數是 {台中每格營收}' if 租 is not None else ''),
        '最多': f'{f(round(營))} − {f(round(成))} ＝ {f(y["最多能付"])}（照台中中位數營收，扣營運成本後剩下的，就是最多能付的月租金）',
    }
    return y

